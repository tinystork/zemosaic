def _run_cell(manifest, canvas, row, col):
    _cell, _patch, mem = zsw.build_cell_context(manifest, canvas, row, col, 5, 4)
    keys = list(mem.patch_ids)
    _gate_or_skip(len(keys))
    _ensure_fixtures(keys)
    prepared = {k: _prepared(k) for k in keys}
    return zx.run_cell_executor(
        manifest, canvas, prepared, row, col, zx.ExecutorConfig(),
        nx=5, ny=4,
    )


@pytest.fixture(scope="module")
def corner_exec(manifest, canvas):
    return _run_cell(manifest, canvas, 0, 0)


