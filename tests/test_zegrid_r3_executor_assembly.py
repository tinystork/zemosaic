def test_assembly_exact_one_owner_synthetic(canvas):
    """Assembly places each core exactly once; disjoint + exhaustive, no gaps."""
    nx, ny = 5, 4
    layout = zg.build_layout(canvas, nx, ny)
    cores: dict[str, dict] = {}
    for row, col, cid in zx.cell_order(canvas, nx, ny):
        b = layout.cell_bounds(row, col, canvas)
        h, w = b.height, b.width
        cores[cid] = {
            "science_core": np.full((h, w, 3), 1.0, dtype=np.float32),
            "surviving_sample_count_core": np.full((h, w, 3), 3, dtype=np.int32),
            "n_eff_support_core": np.full((h, w), 3.0, dtype=np.float64),
            "support_w1_core": np.full((h, w), 1.0, dtype=np.float64),
            "support_w2_core": np.full((h, w), 1.0, dtype=np.float64),
            "valid_mask_core": np.full((h, w, 3), True, dtype=bool),
        }
    a = zm.assemble_canvas(canvas, nx, ny, cores)
    seen = zm.verify_disjoint_exhaustive(a)
    assert int(seen.min()) == 1 and int(seen.max()) == 1
    assert a.hole_pixels == 0
    assert a.incomplete_cells == []
    # Coverage/support planes preserved (never inferred from brightness).
    assert a.stack_depth.shape == (canvas.height, canvas.width)
    assert int(a.stack_depth.min()) == 3 and int(a.stack_depth.max()) == 3
    assert np.isfinite(a.n_eff_support).all()
    assert a.science.shape == (canvas.height, canvas.width, 3)


def test_assembly_holes_explicit(manifest, canvas):
    """A missing Cell leaves an explicit coverage==0 hole (never silently filled)."""
    nx, ny = 5, 4
    layout = zg.build_layout(canvas, nx, ny)
    cores: dict[str, dict | None] = {}
    for row, col, cid in zx.cell_order(canvas, nx, ny):
        if cid == "r0000c0000":
            cores[cid] = None  # incomplete cell
            continue
        b = layout.cell_bounds(row, col, canvas)
        h, w = b.height, b.width
        cores[cid] = {
            "science_core": np.full((h, w, 3), 1.0, dtype=np.float32),
            "surviving_sample_count_core": np.full((h, w, 3), 3, dtype=np.int32),
            "n_eff_support_core": np.full((h, w), 3.0, dtype=np.float64),
            "support_w1_core": np.full((h, w), 1.0, dtype=np.float64),
            "support_w2_core": np.full((h, w), 1.0, dtype=np.float64),
            "valid_mask_core": np.full((h, w, 3), True, dtype=bool),
        }
    a = zm.assemble_canvas(canvas, nx, ny, cores)
    # The missing cell's core is a hole.
    b = layout.cell_bounds(0, 0, canvas)
    assert a.hole_pixels == b.width * b.height
    assert a.incomplete_cells == ["r0000c0000"]
    # Science is NaN inside the hole, finite elsewhere.
    hole = a.science[b.y0:b.y1, b.x0:b.x1]
    assert np.isnan(hole).all()
    # ownership: 19 cells each owned once; the missing cell owned 0 times.
    assert int(a.owner[b.y0:b.y1, b.x0:b.x1].max()) == 0
    assert int(a.owner.max()) == 1


def test_assembly_shape_mismatch_raises(manifest, canvas):
    """A core whose shape does not match its layout bounds raises."""
    nx, ny = 2, 1
    layout = zg.build_layout(canvas, nx, ny)
    b = layout.cell_bounds(0, 0, canvas)
    bad = {
        # Wrong height -> placement would silently corrupt the canvas; must raise.
        "science_core": np.full((b.height - 1, b.width, 3), 1.0, dtype=np.float32),
        "surviving_sample_count_core": np.full((b.height, b.width, 3), 1, dtype=np.int32),
        "n_eff_support_core": np.full((b.height, b.width), 1.0, dtype=np.float64),
        "support_w1_core": np.full((b.height, b.width), 1.0, dtype=np.float64),
        "support_w2_core": np.full((b.height, b.width), 1.0, dtype=np.float64),
        "valid_mask_core": np.full((b.height, b.width, 3), True, dtype=bool),
    }
    with pytest.raises(AssertionError):
        zm.assemble_canvas(canvas, nx, ny, {"r0000c0000": bad})


