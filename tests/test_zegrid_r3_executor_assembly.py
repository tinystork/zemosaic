def _load_persisted_layout(out_dir: str):
    out = Path(out_dir)
    manifest_path = out / "assembly_manifest.json"
    if not manifest_path.exists():
        pytest.skip(f"no R3 assembly manifest at {out_dir}")
    return json.loads(manifest_path.read_text())


