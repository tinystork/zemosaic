def test_m16_depth_guard():
    out = Path("/home/tristan/zegrid_r3_m16_outputs")
    manifest_path = out / "assembly_manifest.json"
    if not manifest_path.exists():
        pytest.skip("no M16 R3 assembly manifest (run tools/zegrid_r3/run_executor.py)")
    manifest = json.loads(manifest_path.read_text())
    effs = [
        (cid, c.get("adequacy", {}).get("effective_contributor_count", 0))
        for cid, c in manifest["cells"].items()
        if c.get("status") == zx.STATUS_COMPLETE
    ]
    if not effs:
        pytest.skip("no complete M16 cells to assert depth")
    best = max(effs, key=lambda t: t[1])
    assert best[1] >= 20, (
        f"M16 depth guard BLOCKED: max effective contributors = {best[1]} "
        f"(cell {best[0]}), expected >= 20"
    )
